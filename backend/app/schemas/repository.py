from datetime import datetime
from typing import List, Optional
import uuid
from pydantic import BaseModel, ConfigDict, Field


class RepoImportRequest(BaseModel):
    """
    Request payload to import a GitHub repository.
    Accepts public repository URLs or private repository URLs with a scoped access token.
    Never requests or stores passwords.
    """
    repo_url: str = Field(..., description="HTTPS GitHub repository URL, e.g. https://github.com/owner/repo")
    access_token: Optional[str] = Field(default=None, description="Optional GitHub Personal Access Token for private repositories (never logged or stored)")
    name: Optional[str] = Field(default=None, description="Optional custom display name for the repository")
    branch: Optional[str] = Field(default=None, description="Optional branch or commit to checkout (defaults to default branch)")


class RepoResponse(BaseModel):
    """
    Full repository details and indexing status.
    """
    id: uuid.UUID
    name: str
    repo_url: str
    owner: str
    default_branch: str
    is_private: bool
    status: str
    total_files: int
    total_chunks: int
    total_size_bytes: int
    error_message: Optional[str] = None
    last_indexed_at: Optional[datetime] = None
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)


class RepoImportStatusResponse(BaseModel):
    """
    Current status of repository cloning and vector indexing.
    """
    id: uuid.UUID
    name: str
    status: str
    total_files: int
    total_chunks: int
    total_size_bytes: int
    error_message: Optional[str] = None
    last_indexed_at: Optional[datetime] = None


class CodeChunkMetadata(BaseModel):
    """
    Source code chunk with positional metadata.
    """
    chunk_id: str
    repo_id: str
    file_path: str
    language: str
    start_line: int
    end_line: int
    line_range: str
    content: str


class RetrievedChunk(BaseModel):
    """
    Code snippet retrieved from the FAISS vector index.
    """
    file_path: str
    line_range: str
    language: str
    score: float
    content: str


class RepoChatRequest(BaseModel):
    """
    Question asked by the user against the repository's indexed code.
    """
    question: str = Field(..., min_length=2, description="Natural language question about repository code")
    top_k: int = Field(default=4, ge=1, le=10, description="Number of relevant code chunks to retrieve")


class RepoChatResponse(BaseModel):
    """
    RAG answer generated by Groq citing retrieved file paths and line ranges.
    """
    question: str
    answer: str
    sources: List[RetrievedChunk] = Field(default_factory=list)
    evidence_sufficient: bool = True
